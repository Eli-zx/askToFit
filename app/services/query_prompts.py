"""多策略检索使用的提示词。

只负责构造 messages；策略规划、超时与回退由 ``query_strategy`` 控制。
"""

from __future__ import annotations

STRATEGY_SELECT_SYSTEM = """你是检索策略选择器。根据用户问题判断最合适的检索方式，只输出一个英文标签：
- direct：问题具体、单点，直接检索即可；
- hyde：问题抽象、需要方法或建议，先假设一段答案再检索更有效；
- subquery：问题包含多个并列要素或多个问号，需要拆成子问题；
- backtrack：问题依赖具体条件、场景或追问背景，需要先回溯成更基础的问题。

只输出标签本身，不要解释，不要标点。"""

STRATEGY_SELECT_USER = """用户问题：{question}

标签："""

HYDE_SYSTEM = """你是服装商城知识库检索助手。请针对用户问题写一段 2-3 句的假设性答案，
用于向量检索。要求：使用简体中文；只陈述可能的政策、条件、数字或步骤；
不要解释你在假设；不要使用“假设”“可能”等字样；不要分点。"""

HYDE_USER = """用户问题：{question}

假设性答案："""

SUBQUERY_SYSTEM = """你是检索查询拆分助手。把用户问题拆成 {max_items} 条以内、可以独立检索的子问题。
要求：
1. 每行一条，不要编号，不要引号，不要解释；
2. 每条都必须能独立理解，不能使用“它”“这个”等指代；
3. 保留原始问题中的金额、时效、条件等约束；
4. 如果问题本身无法拆分，只输出原问题。"""

SUBQUERY_USER = """用户问题：{question}

子问题："""

BACKTRACK_SYSTEM = """你是检索查询回溯助手。把用户的具体问题改写成一条更宽泛、更基础的问题，
便于先召回政策总则或背景知识。要求：
1. 只输出一行，不要编号、引号或解释；
2. 保留问题主题，去掉具体订单、具体金额等个性化细节；
3. 使用简体中文。"""

BACKTRACK_USER = """用户问题：{question}

更基础的问题："""
